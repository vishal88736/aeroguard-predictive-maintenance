"""Disposable synthetic CPU workspace for real MLOps browser workflows."""

import argparse
import json
import os
from pathlib import Path
import sys
import tempfile

os.environ.setdefault("MLFLOW_DISABLE_TELEMETRY", "true")
os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
os.environ.setdefault("OMP_NUM_THREADS", "2")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "2")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import numpy as np
import uvicorn
from aeroguard.api import create_app
from aeroguard.baseline import evaluate_model, train_model
from test_ag_baseline import write_fixture


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8792)
    args = parser.parse_args()
    (ROOT / "runtime").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="mlops-ui-fixture-", dir=ROOT / "runtime") as folder:
        root = Path(folder)
        write_fixture(root / "data", engines=50)
        (root / "data/provenance.json").write_text(json.dumps({"dataset": "Isolated synthetic software-test fixture", "acquisition": "Generated by tests; not a NASA benchmark result"}))
        model = train_model({"subsets": ["FD001"], "iterations": 10, "window": 15, "track_mlflow": True}, root / "data", root / "artifacts")
        evaluate_model(model["run_id"], root / "data", root / "artifacts")
        write_fixture(root / "incoming", engines=55)
        observed = root / "observed.txt"
        observed.write_bytes((root / "data/test_FD001.txt").read_bytes())
        complete = root / "complete.txt"
        complete.write_bytes((root / "incoming/train_FD001.txt").read_bytes())
        bad = np.loadtxt(observed); bad[:, 5:10] = np.nan
        damaged = root / "damaged.txt"; np.savetxt(damaged, bad)
        app = create_app(root / "data", root / "artifacts", root / "runtime")
        app.state.service.promote(model["run_id"])
        settings = app.state.service.repo.settings().model_dump()
        settings["workspace_name"] = "Isolated MLOps software-test fixture"
        app.state.service.repo.save_settings(settings)
        print(json.dumps({"mlops_fixture": True, "workspace": str(root), "observed": str(observed), "complete": str(complete),
                          "damaged": str(damaged), "original_run_id": model["run_id"], "source": "Synthetic fixture software verification, not NASA metrics or GPU training"}), flush=True)
        uvicorn.run(app, host="127.0.0.1", port=args.port)
